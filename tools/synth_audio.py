def make_draw(seed):  # katana drawn from the saya: scrape rising to a short ring-out
    r = rng(seed)
    dur = 0.62
    n = int(dur * SR)
    t = np.arange(n) / SR
    base = noise(n, r)
    f = np.clip(t / dur, 0, 1)
    scrape = bp(base, 1800, 6500) * (0.4 + 0.6 * f) * np.clip((dur - t) / 0.08, 0, 1)
    rub = bp(base, 700, 1600) * (1 - f) * 0.6
    mod = 0.55 + 0.45 * np.abs(lp(noise(n, r), 25))
    x = (scrape + rub) * mod * 0.45 * attack(n, 0.03)
    ring = modal([2250, 3980, 6120], [0.35, 0.22, 0.12], [0.35, 0.25, 0.15], 0.9, r, jitter=0.02)
    out = np.r_[x, np.zeros(int(0.9 * SR))]
    put(out, ring, dur - 0.04, 0.55)
    put(out, modal([240, 450], [0.04, 0.025], [0.6, 0.3], 0.15, r), 0.0, 0.3)  # saya mouth
    return out


