def make_bullet_impact(seed, surface):
    r = rng(seed)
    n = int(1.1 * SR)
    x = np.zeros(n)
    if surface == "wood":
        put(x, modal([260, 480, 870, 1500], [0.045, 0.03, 0.02, 0.012], [0.8, 0.5, 0.3, 0.2], 0.4, r, jitter=0.05), 0.0, 0.9)
        crack = hp(noise(int(0.04 * SR), r), 900) * edecay(int(0.04 * SR), 0.006)
        put(x, crack, 0.0, 0.4)
        put(x, lp(noise(int(0.25 * SR), r), 700) * edecay(int(0.25 * SR), 0.05), 0.0, 0.5)
    elif surface == "stone":
        put(x, hp(noise(int(0.03 * SR), r), 2500) * edecay(int(0.03 * SR), 0.004), 0.0, 0.6)
        put(x, modal([1700, 2900, 4400], [0.05, 0.035, 0.02], [0.5, 0.4, 0.3], 0.35, r, jitter=0.05), 0.0, 0.6)
        put(x, lp(noise(int(0.12 * SR), r), 1800) * edecay(int(0.12 * SR), 0.02), 0.0, 0.4)
        chips = (r.random(int(0.35 * SR)) < 0.0008).astype(float)
        put(x, signal.fftconvolve(chips, modal([3200, 5200], [0.003, 0.002], [0.5, 0.3], 0.02, r))[:int(0.35 * SR)], 0.02, 0.5)
        # whining ricochet
        put(x, sweep(5200, 2400, 0.12, 0.4) * edecay(int(0.4 * SR), 0.1), 0.012, 0.12)
    elif surface == "soil":
        put(x, sweep(130, 60, 0.04, 0.3) * edecay(int(0.3 * SR), 0.06), 0.0, 0.9)
        put(x, lp(noise(int(0.3 * SR), r), 900) * edecay(int(0.3 * SR), 0.05), 0.0, 0.5)
        spray = (r.random(int(0.5 * SR)) < 0.0012).astype(float)
        put(x, signal.fftconvolve(spray, bp(noise(260, r), 1500, 6000) * edecay(260, 0.0015))[:int(0.5 * SR)], 0.015, 0.3)
