def make_creak(seed, variant):
    r = rng(seed)
    dur = [0.9, 1.4, 0.65, 1.1][variant % 4]
    n = int(dur * SR)
    t = np.arange(n) / SR
    rate = np.interp(t / dur, [0, 0.5, 1], [28 + 10 * variant, 70 + 12 * variant, 36])
    phase = np.cumsum(rate) / SR
    pulses = np.zeros(n)
    idx = np.where(np.diff(np.floor(phase)) > 0)[0]
    pulses[idx] = 1.0 + r.uniform(-0.3, 0.3, len(idx))
    res = [(330 + 60 * variant, 0.018), (780 + 90 * variant, 0.012), (1320, 0.008), (2100, 0.005)]
    kern_t = tt(0.06)
    kernel = sum(a * np.sin(2 * np.pi * f * kern_t) * np.exp(-kern_t / d)
                 for (f, d), a in zip(res, [1.0, 0.6, 0.35, 0.2]))
    x = signal.fftconvolve(pulses, kernel)[:n]
    x *= np.sin(np.pi * t / dur) ** 1.2
    return x


