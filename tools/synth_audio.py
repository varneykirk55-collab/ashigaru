    env = periodic_noise(L2, lambda f: np.where((f > 0.2) & (f < 2.5), 1.0, 0.0) / np.maximum(f, 0.2), 22, sr2)
    env = 0.45 + 0.55 * np.clip(env / 2.2 + 0.4, 0, 1)
    leaves = leaves * env * periodic_lfo(L2, sr2, [1, 2, 4, 6], 23, 0.6)
    save_loop("foliage_loop", leaves, sr2, -30)

    sr3 = 24000
    L3 = 20
