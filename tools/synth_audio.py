def vowel_filter(src, vowel, sr=SR):
    out = np.zeros_like(src)
    for f, bw, g in FORM[vowel]:
        out += g * bp(src, max(60, f - bw), f + bw, 2, sr)
    return out


def voice(dur, f0a, f0b, v0, v1, breath, seed, env_fn, rough=0.0, vib=0.0):
    r = rng(seed)
    n = int(dur * SR)
    t = np.arange(n) / SR
    f0 = np.linspace(f0a, f0b, n) * (1 + 0.012 * lp(noise(n, r), 8) * 6)
    if vib:
        f0 = f0 * (1 + vib * np.sin(2 * np.pi * 5.5 * t))
    ph = np.cumsum(f0) / SR
    glottal = 2 * (ph % 1.0) - 1
    glottal = lp(glottal, 2400, 1) + 0.04 * r.standard_normal(n) * breath
    if rough:
        glottal *= 1 - rough * (0.5 + 0.5 * np.sin(2 * np.pi * 38 * t + r.uniform(0, 6)))
    a = vowel_filter(glottal, v0)
    b = vowel_filter(glottal, v1)
    w = t / dur
    y = a * (1 - w) + b * w
    y += breath * 0.05 * bp(noise(n, r), 900, 3800)
    return y * env_fn(t, dur)


