def bird_notes(r, notes, kind):
    n = int(sum(d + g for _, _, d, g in notes) * SR) + int(0.4 * SR)
    x = np.zeros(n)
    at = 0.0
    for f0, f1, d, g in notes:
        k = int(d * SR)
        tn = np.arange(k) / SR
        f = np.linspace(f0, f1, k)
        if kind == "trill":
            f = f * (1 + 0.04 * np.sin(2 * np.pi * 38 * tn))
        elif kind == "warble":
            f = f * (1 + 0.025 * np.sin(2 * np.pi * 24 * tn))
        ph = 2 * np.pi * np.cumsum(f) / SR
        note = (np.sin(ph) + 0.25 * np.sin(2 * ph)) * np.sin(np.pi * tn / d) ** 1.4
        put(x, note, at, 1.0)
        at += d + g
    return x


