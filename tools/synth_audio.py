# ----------------------------------------------------------------------------- ambience (loops)
def periodic_noise(seconds, shape, seed, sr):
    r = rng(seed)
    n = int(seconds * sr)
    f = np.fft.rfftfreq(n, 1 / sr)
    mag = shape(f)
    ph = r.uniform(0, 2 * np.pi, len(f))
    spec = mag * np.exp(1j * ph)
    spec[0] = 0
    x = np.fft.irfft(spec, n)
    return x / (np.std(x) + 1e-12)


def periodic_lfo(seconds, sr, harmonics, seed, depth):
    """Seamless slow modulation: integer number of cycles per loop."""
    r = rng(seed)
    n = int(seconds * sr)
    t = np.arange(n) / sr
    m = np.zeros(n)
    for k in harmonics:
        m += np.sin(2 * np.pi * k * t / seconds + r.uniform(0, 6.28)) / np.sqrt(k)
    m = m / (np.max(np.abs(m)) + 1e-9)
    return 1 - depth * (0.5 - 0.5 * m)


def band_shape(lo, hi, slope=2.0):
    def shape(f):
        f = np.maximum(f, 1.0)
        m = 1.0 / (1 + (lo / f) ** 4) / (1 + (f / hi) ** slope)
        return m / np.sqrt(f)
    return shape


def save_loop(name, x, sr, rms_db=-26.0):
    x = x / (np.sqrt(np.mean(x ** 2)) + 1e-12) * 10 ** (rms_db / 20)
    peak = np.max(np.abs(x))
    if peak > 0.9:
        x = x / peak * 0.9
    d = os.path.join(OUT, "ambience")
    os.makedirs(d, exist_ok=True)
    wavfile.write(os.path.join(d, name + ".wav"), sr, (np.clip(x, -1, 1) * 32767).astype(np.int16))
    MANIFEST[name] = {"group": "ambience", "seconds": round(len(x) / sr, 3), "rms_db": rms_db, "rate": sr, "loop": True}


def make_loops():
    sr = 24000
    L = 24
    wind = periodic_noise(L, band_shape(90, 700, 2.4), 11, sr)
    wind *= periodic_lfo(L, sr, [1, 2, 3, 5], 12, 0.7)
    gust_hi = periodic_noise(L, band_shape(700, 2600, 2.0), 13, sr) * 0.35 * periodic_lfo(L, sr, [2, 3, 4], 14, 0.9)
    save_loop("wind_loop", wind + gust_hi, sr, -26)

    sr2 = 32000
    L2 = 28
