"""Procedural sound design for ASHIGARU.

Every sound in assets/audio is generated by this script (numpy/scipy only).
No recordings, sample libraries or third-party audio are used, so there is nothing to
attribute: the output is original work offered under CC0 1.0.

Usage: python3 tools/synth_audio.py [out_dir]   (default: assets/audio)
Deterministic: fixed seeds, so re-running reproduces the same files.
"""
