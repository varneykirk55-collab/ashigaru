def make_swing(seed, strong=True):
    r = rng(seed)
    dur = r.uniform(0.34, 0.42) if strong else 0.26
    n = int(dur * SR)
    t = np.arange(n) / SR
    center = np.interp(t / dur, [0, 0.35, 0.6, 1], [450, 1500, 2600, 900]) * r.uniform(0.9, 1.1)
    base = noise(n, r)
    # time-varying band by cross-fading three fixed bands along the sweep
    lo = bp(base, 250, 900)
    mid = bp(base, 800, 2600)
    hi = bp(base, 2200, 7500)
    w = (t / dur)
    a = np.clip(1 - w * 2.2, 0, 1)
    c = np.clip(1 - np.abs(w - 0.5) * 3.2, 0, 1)
    b = np.clip((w - 0.4) * 2.0, 0, 1) * np.clip(1 - (w - 0.7) * 2.5, 0, 1)
    env = np.sin(np.pi * np.clip(w, 0, 1)) ** 1.6 * np.clip(1 - w, 0, 1) ** 0.3
    y = (lo * (a * 0.5 + c * 0.7) + mid * (c * 0.9 + a * 0.4) + hi * b * 0.6) * env
    # thin blade hum riding the air cut
    y += 0.08 * np.sin(2 * np.pi * np.cumsum(center) / SR) * env
    return y


