def make_powder(seed):  # pouring powder: dense granular hiss with a brief tapering
    r = rng(seed)
    dur = 0.75
    n = int(dur * SR)
    t = np.arange(n) / SR
    hiss = bp(noise(n, r), 2500, 9500)
    grain = (r.random(n) < 0.006).astype(float)
    grain = signal.fftconvolve(grain, edecay(300, 0.0008))[:n]
    env = np.clip(t / 0.06, 0, 1) * np.clip((dur - t) / 0.3, 0, 1) ** 1.2
    x = (0.3 * hiss + 1.1 * hp(grain * noise(n, r), 1500)) * env
    put(x, modal([420, 800], [0.025, 0.015], [0.4, 0.2], 0.08, r), 0.0, 0.3)  # horn flask tap
    return x


def make_ram_in(seed):  # ramrod sliding down the barrel
    r = rng(seed)
    dur = 0.85
    n = int(dur * SR)
    t = np.arange(n) / SR
    fr = 1300 + 900 * t / dur
    scrape = np.zeros(n)
    ph = 0
    for lo, hi in [(900, 1700), (1800, 3400)]:
        scrape += bp(noise(n, r), lo, hi, 2)
    mod = 0.6 + 0.4 * np.abs(lp(noise(n, r), 14))
    env = attack(n, 0.05) * np.clip((dur - t) / 0.2, 0, 1)
    barrel = np.sin(2 * np.pi * (170 + 40 * t / dur) * t) * 0.35 * env
    return (scrape * mod * 0.12 + barrel * 0.5 + lp(noise(n, r), 400) * 0.1 * env)


def make_ram_tamp(seed):  # two firm seating strokes
    r = rng(seed)
    x = np.zeros(int(0.9 * SR))
    for at, g in [(0.05, 1.0), (0.38, 0.85)]:
        thump = sweep(160, 85, 0.03, 0.2) * edecay(int(0.2 * SR), 0.06)
        ring = modal([880, 1480, 2230], [0.05, 0.03, 0.02], [0.5, 0.3, 0.2], 0.2, r, jitter=0.03)
        body = lp(noise(int(0.1 * SR), r), 900) * edecay(int(0.1 * SR), 0.02)
        put(x, thump, at, 0.9 * g)
        put(x, ring, at, 0.55 * g)
        put(x, body, at, 0.5 * g)
    return x


